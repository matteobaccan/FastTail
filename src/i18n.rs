use serde::{Deserialize, Serialize};

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum Language {
    En,
    It,
    Fr,
    Es,
    Zh,
}

impl Language {
    pub fn name(&self) -> &'static str {
        match self {
            Language::En => "English",
            Language::It => "Italiano",
            Language::Fr => "Français",
            Language::Es => "Español",
            Language::Zh => "中文 (简体)",
        }
    }

    pub fn code(&self) -> &'static str {
        match self {
            Language::En => "en",
            Language::It => "it",
            Language::Fr => "fr",
            Language::Es => "es",
            Language::Zh => "zh",
        }
    }

    pub fn from_code(code: &str) -> Self {
        if code.starts_with("it") {
            Language::It
        } else if code.starts_with("fr") {
            Language::Fr
        } else if code.starts_with("es") {
            Language::Es
        } else if code.starts_with("zh") {
            Language::Zh
        } else {
            Language::En
        }
    }

    pub fn detect() -> Self {
        // Check environment variables first
        for var in &["LC_ALL", "LC_MESSAGES", "LANG"] {
            if let Ok(val) = std::env::var(var) {
                let lower = val.to_lowercase();
                if lower.starts_with("it") {
                    return Language::It;
                } else if lower.starts_with("fr") {
                    return Language::Fr;
                } else if lower.starts_with("es") {
                    return Language::Es;
                } else if lower.starts_with("zh") {
                    return Language::Zh;
                }
            }
        }

        #[cfg(windows)]
        {
            #[link(name = "kernel32")]
            extern "system" {
                fn GetUserDefaultUILanguage() -> u16;
            }
            let lang_id = unsafe { GetUserDefaultUILanguage() };
            let primary_lang = lang_id & 0x3ff;
            match primary_lang {
                0x10 => return Language::It,
                0x0c => return Language::Fr,
                0x0a => return Language::Es,
                0x04 => return Language::Zh,
                _ => {}
            }
        }

        Language::En
    }
}

